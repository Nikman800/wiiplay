"""Generate library translation-unit splits (.text) from dtk/library_matches.tsv.

Each reference source file whose matched functions form one contiguous block of our functions
becomes a unit named after the reference path. A block may absorb unmatched functions only
when they sit between two functions of the same unit. Files seen in two separate places are
reported and left to dtk's auto-splitting. Output replaces the generated block in
config/RHAE01/splits.txt between the BEGIN/END markers.

Usage: make_lib_splits.py <root>
"""
import collections
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rhae_libs import RHAE_LIBS  # noqa: E402

LINE = re.compile(r"^(\S+) = (\S+):0x([0-9A-F]+); // (.*)$")
UNIT_HEADER = re.compile(r"^(?!Sections:)(\S.*):\s*$")
BEGIN = "// BEGIN library units (generated by tools/make_lib_splits.py)"
END = "// END library units"
GAME_START, GAME_END = 0x80182E90, 0x802E9CC0
# Units dtk detects itself (from .ctors/extab); generating them would conflict with its split.
DTK_DETECTED = {"__init_cpp_exceptions.cpp"}


def main():
    root = Path(sys.argv[1])
    funcs = []
    for l in (root / "config/RHAE01/symbols.txt").read_text(encoding="utf-8").splitlines():
        m = LINE.match(l)
        if m and m.group(2) == ".text" and "type:function" in m.group(4):
            size = int(re.search(r"size:0x([0-9A-F]+)", m.group(4)).group(1), 16)
            funcs.append((int(m.group(3), 16), size))
    funcs.sort()
    unit_at = {int(r["address"], 16): r["ref_unit"]
               for r in csv.DictReader(open(root / "dtk/library_matches.tsv", encoding="utf-8"), delimiter="\t")
               if r["ref_unit"]}
    cluster = root / "dtk/cluster_matches.tsv"
    if cluster.exists():  # ordered-alignment matches (tools/fill_clusters.py)
        for r in csv.DictReader(open(cluster, encoding="utf-8"), delimiter="\t"):
            if r["ref_unit"]:
                unit_at.setdefault(int(r["address"], 16), r["ref_unit"])
    game_names = root / "dtk/game_ref_names.tsv"
    if game_names.exists():  # shared RP framework units from strict Wii Sports matches
        for r in csv.DictReader(open(game_names, encoding="utf-8"), delimiter="\t"):
            if r["ref_unit"]:
                unit_at[int(r["address"], 16)] = r["ref_unit"]
    # walk functions in order, grouping maximal blocks with one unit (unmatched allowed inside)
    blocks, cur = [], None
    for addr, size in funcs:
        if GAME_START <= addr < GAME_END and addr not in unit_at:
            cur = None  # unmatched game code ends any open unit
            continue
        u = unit_at.get(addr)
        if u is None:
            if cur:
                cur["pending"].append((addr, size))
            continue
        if cur and cur["unit"] == u:
            cur["end"] = addr + size
            cur["pending"] = []
            cur["n"] += 1
        else:
            cur = dict(unit=u, start=addr, end=addr + size, pending=[], n=1)
            blocks.append(cur)
    seen = collections.Counter(b["unit"] for b in blocks)
    split_ok = [b for b in blocks if seen[b["unit"]] == 1 and Path(b["unit"]).name not in DTK_DETECTED]
    repeated = sorted(u for u, c in seen.items() if c > 1)
    # extend each unit's end to the next function start when only padding lies between
    starts = [a for a, _ in funcs]
    import bisect
    for b in split_ok:
        k = bisect.bisect_left(starts, b["end"])
        if k < len(starts) and starts[k] - b["end"] < 0x20:
            b["end"] = starts[k]
    path = root / "config/RHAE01/splits.txt"
    # dtk rewrites splits.txt and drops comments, so markers can't be relied on. Regenerate every
    # unit except hand-maintained ones (a real source file under src/) and dtk-detected ones; a
    # unit whose reference name changed between runs would otherwise linger as a stale duplicate.
    kept, skip = [], False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("//"):
            continue
        header = UNIT_HEADER.match(line)
        if header:
            name = header.group(1)
            # blocks of libraries laid out like Rhae (every section) are kept as written
            manual = ((root / "src" / name).exists() or Path(name).name in DTK_DETECTED
                      or name.startswith(RHAE_LIBS))
            skip = not manual and not name.startswith("auto_")
        if not skip:
            kept.append(line)
    # a kept (hand-maintained) unit already has its block: generating it again would duplicate it
    kept_names = {UNIT_HEADER.match(l).group(1) for l in kept if UNIT_HEADER.match(l)}
    # ...and so would one whose code a kept block covers under another name
    kept_text = [(int(m.group(1), 16), int(m.group(2), 16)) for l in kept
                 if (m := re.match(r"\s+\.text\s+start:0x([0-9A-Fa-f]+)\s+end:0x([0-9A-Fa-f]+)", l))]
    text = [BEGIN]
    for b in split_ok:
        if b["unit"] in kept_names or any(a < b["end"] and b["start"] < e for a, e in kept_text):
            continue
        text += ["", f"{b['unit']}:", f"\t.text       start:0x{b['start']:08X} end:0x{b['end']:08X}"]
    text.append(END)
    s = "\n".join(kept).rstrip("\n") + "\n\n" + "\n".join(text) + "\n"
    path.write_text(s, encoding="utf-8", newline="\n")
    covered = sum(b["n"] for b in split_ok)
    print(f"{len(split_ok)} units written ({covered} matched functions); "
          f"{len(repeated)} reference files appear in more than one place, left unsplit")
    for u in repeated[:15]:
        print("  repeated:", u)


if __name__ == "__main__":
    main()
